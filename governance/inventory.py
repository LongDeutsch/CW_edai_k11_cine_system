def assert_catalog_matches_sources() -> list[str]:
    """Trả danh sách lệch giữa inventory và source. Rỗng nghĩa là khớp."""
    problems = []
    if sorted(fastapi_routes()) != sorted(expected_routes()):
        problems.append(f"route lệch: source={fastapi_routes()} inventory={list(expected_routes())}")
    if airflow_task_ids() != list(expected_tasks()):
        problems.append(f"task lệch: source={airflow_task_ids()} inventory={list(expected_tasks())}")
    return problems
