@dataclass(frozen=True)
class Dataset:
    id: str
    name: str
    location: str
    grain: str
    business_keys: tuple[str, ...]
    update_mode: str
    owner: str
    quality: tuple[str, ...]
    freshness: str
    lineage_status: str
    evidence: tuple[tuple[str, str], ...]
    schema_ref: tuple[str, str, str] | None = None
    writer_columns: tuple[tuple[str, str], ...] = ()
    root: bool = False


@dataclass(frozen=True)
class Edge:
    upstream: str
    downstream: str
    evidence: tuple[str, str]
    kind: str


def datasets() -> tuple[Dataset, ...]:
    return _DATASETS


def edges() -> tuple[Edge, ...]:
    return _EDGES


def schema_of(dataset: Dataset) -> list[tuple[str, str]]:
    if dataset.schema_ref is None:
        return []
    kind, source, name = dataset.schema_ref
    if kind == "spark":
        columns = spark_tables(source)[name]
    elif kind == "clickhouse":
        columns = clickhouse_tables()[name]
    elif kind == "flink":
        columns = flink_tables()[name]
    elif kind == "audit":
        columns = audit_tables()[name]
    else:
        raise KeyError(kind)
    return [*columns, *dataset.writer_columns]


def production_table_names() -> dict[str, set[str]]:
    """Tên bảng production mà DDL hoặc writer khai báo."""
    return {
        "bronze": set(spark_tables("storage/lakehouse/bronze/raw_tables.sql")) | set(audit_tables()),
        "silver": set(spark_tables("storage/lakehouse/silver/stg_tables.sql")) | set(flink_tables()),
        "gold": set(spark_tables("storage/lakehouse/gold/gold_tables.sql")),
        "clickhouse": set(clickhouse_tables()),
    }


def expected_routes() -> tuple[str, ...]:
    return tuple(item.location.removeprefix("GET ") for item in _DATASETS if item.id.startswith("api."))


def expected_tasks() -> tuple[str, ...]:
    job = next(item for item in _DATASETS if item.id == "airflow.cinestream_daily_batch_lakehouse")
    return tuple(part.strip() for part in job.grain.split(",") if part.strip())


